def update_php_file(file_path, data):
    if not os.path.exists(file_path):
        print(f"File not found: {file_path}")
        return

    with open(file_path, 'r', encoding='utf-8') as f:
        content = f.read()

    # We will append missing keys or update blocks inside return array
    # Let's parse PHP array or inject keys smartly.
    # Since PHP array files return [...]; we can read the lines before ]; and inject our array sections if missing.
    for section_key, section_dict in data.items():
        pattern = rf"'{section_key}'\s*=>\s*\["
        if re.search(pattern, content):
            # Section exists, update/add individual keys inside section
            for k, v in section_dict.items():
                k_pattern = rf"'{re.escape(k)}'\s*=>\s*.*"
                escaped_v = v.replace("'", "\\'")
                if re.search(k_pattern, content):
                    content = re.sub(k_pattern, f"'{k}' => '{escaped_v}',", content)
                else:
                    # Inject key into section block
                    inject_pos = re.search(pattern, content).end()
                    content = content[:inject_pos] + f"\n        '{k}' => '{escaped_v}'," + content[inject_pos:]
        else:
            # Section does not exist, append section before last ];
            last_bracket = content.rfind("];")
            if last_bracket != -1:
                section_str = f"    '{section_key}' => [\n"
                for k, v in section_dict.items():
                    escaped_v = v.replace("'", "\\'")
                    section_str += f"        '{k}' => '{escaped_v}',\n"
                section_str += "    ],\n"
                content = content[:last_bracket] + section_str + content[last_bracket:]

    with open(file_path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"Updated {file_path}")

for lang, data in translations.items():
    file_path = os.path.join(base_dir, lang, "ui.php")
    update_php_file(file_path, data)
